DO $$
DECLARE
  v_head uuid := (SELECT profile_id FROM it_members WHERE role = 'head' LIMIT 1);
  v_m uuid;
BEGIN
  IF EXISTS (SELECT 1 FROM it_issues WHERE legacy_story_id IS NOT NULL) THEN RETURN; END IF;
  INSERT INTO it_milestones (name, goal, start_date, end_date, status, owner_id, created_by)
  VALUES ('Partner Promo & EV Reporting', 'Institutional partners, promo codes and discounts, partner trip attribution, EV impact and monthly partner reports.',
          '2026-10-19', '2026-11-01', 'planned', v_head, (SELECT id FROM profiles WHERE role = 'managing_director' AND is_active LIMIT 1))
  RETURNING id INTO v_m;

  INSERT INTO it_issues (title, description, type, areas, priority, status, assignee_id, milestone_id, source, planned, labels, acceptance_criteria, legacy_story_id, created_by, created_at, updated_at, started_at, completed_at)
  SELECT
    trim(regexp_replace(COALESCE(NULLIF(trim(s.title), ''), s.need), '^\d+\.\s*', '')),
    NULLIF(concat_ws(E'\n\n',
      CASE WHEN s.persona IS NOT NULL AND s.need IS NOT NULL AND s.source <> 'flagged' THEN 'As a ' || s.persona || ', I need ' || s.need || COALESCE(', so that ' || s.benefit, '') || '.' END,
      s.details), ''),
    CASE WHEN s.title ILIKE '%methodology%' THEN 'research' WHEN s.title ILIKE '%test and launch%' THEN 'chore' ELSE 'feature' END,
    CASE
      WHEN s.title ILIKE '%Corporate Account Deposit%' THEN ARRAY['backend', 'app_rider']
      WHEN s.title ILIKE '%Shift Handover%' THEN ARRAY['app_driver', 'backend']
      WHEN s.title ILIKE '%Fleet Manager Page%' THEN ARRAY['app_driver']
      WHEN s.title ILIKE '%Driver Withdrawals%' OR s.title ILIKE '%Outstanding Driver Commission%' THEN ARRAY['backend', 'app_driver']
      WHEN s.title ILIKE '%Validate the promo code%' OR s.title ILIKE '%apply the partner discount%' THEN ARRAY['app_rider', 'backend']
      WHEN s.title ILIKE '%institutional partners%' OR s.title ILIKE '%partner promo codes%' THEN ARRAY['dashboard', 'backend']
      WHEN s.title ILIKE '%qualifying trip%' OR s.title ILIKE '%eligibility and misuse%' THEN ARRAY['backend']
      WHEN s.title ILIKE '%dashboard overview%' OR s.title ILIKE '%Generate and approve monthly%' OR s.title ILIKE '%Call Center booking logs%' THEN ARRAY['dashboard']
      WHEN s.title ILIKE '%analytics, graphs%' THEN ARRAY['dashboard', 'data_ai']
      WHEN s.title ILIKE '%reporting dataset%' OR s.title ILIKE '%Feed completed trips%' OR s.title ILIKE '%Migrate existing partners%' THEN ARRAY['backend', 'data_ai']
      WHEN s.title ILIKE '%carbon%' OR s.title ILIKE '%environmental impact%' THEN ARRAY['data_ai']
      WHEN s.title ILIKE '%Design a beautiful%' THEN ARRAY['design', 'dashboard']
      WHEN s.title ILIKE '%Send monthly reports%' THEN ARRAY['dashboard', 'backend']
      WHEN s.title ILIKE '%partner portal access%' THEN ARRAY['website', 'security']
      WHEN s.title ILIKE '%audit trails%' THEN ARRAY['security', 'backend']
      WHEN s.title ILIKE '%Test and launch%' THEN ARRAY['testing']
      WHEN s.title ILIKE '%vehicle model and energy%' THEN ARRAY['backend', 'admin']
      ELSE '{}'::text[] END,
    CASE s.priority WHEN 'high' THEN 'p1' WHEN 'low' THEN 'p3' ELSE 'p2' END,
    CASE s.status WHEN 'review' THEN 'in_review' WHEN 'in_progress' THEN 'in_progress' WHEN 'done' THEN 'done' ELSE 'backlog' END,
    s.assignee_id,
    CASE WHEN s.source = 'flagged' THEN NULL ELSE v_m END,
    CASE WHEN s.source = 'flagged' THEN 'department' ELSE 'migrated' END,
    true,
    array_remove(ARRAY[CASE WHEN m.name IS NOT NULL AND s.source <> 'flagged' THEN regexp_replace(m.name, ' - .*$', '') END, CASE WHEN s.source <> 'flagged' THEN f.name END], NULL),
    COALESCE(s.acceptance_criteria, '[]'::jsonb),
    s.id, s.created_by, s.created_at, s.updated_at,
    CASE WHEN s.status IN ('in_progress', 'review', 'done') THEN s.updated_at END,
    CASE WHEN s.status = 'done' THEN s.updated_at END
  FROM user_stories s
  LEFT JOIN features f ON f.id = s.feature_id
  LEFT JOIN milestones m ON m.id = f.milestone_id
  ORDER BY s.source DESC, s.created_at;

  -- Flagged ones keep their requester (for the "it's done" email).
  INSERT INTO it_inbox (title, details, persona, acceptance_criteria, submitted_by, submitted_at, status, decided_at, issue_id)
  SELECT i.title, i.description, s.persona, i.acceptance_criteria, s.created_by, s.created_at, 'accepted', now(), i.id
  FROM it_issues i JOIN user_stories s ON s.id = i.legacy_story_id WHERE s.source = 'flagged';
  UPDATE it_issues i SET inbox_id = x.id FROM it_inbox x WHERE x.issue_id = i.id AND i.inbox_id IS NULL;
END $$;

DO $$ BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE it_issues; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE it_inbox; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE it_checkins; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
