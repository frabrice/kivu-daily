  IT or the MD accepts (-> issue), merges, parks or declines them.
- it_checkins: 10:00 and 14:00 Mon-Fri every IT member confirms what they
  are working on (asked by the notifications engine).

The old products / milestones / features / user_stories tables are kept
read-only as history; their 26 stories are copied in as issues.
