CREATE OR REPLACE FUNCTION it_issue_before() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_lead boolean := is_it_lead() OR auth.uid() IS NULL;   -- NULL = migration / service
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.created_by := COALESCE(auth.uid(), NEW.created_by);
    IF auth.uid() IS NOT NULL THEN
      IF is_managing_director() THEN NEW.source := CASE WHEN NEW.source = 'department' THEN 'department' ELSE 'md' END; NEW.planned := true;
      ELSIF v_lead THEN NEW.source := CASE WHEN NEW.source = 'department' THEN 'department' ELSE 'head' END; NEW.planned := true;
      ELSE NEW.source := 'it'; NEW.planned := false;        -- a developer's own work: visible as unplanned
      END IF;
    END IF;
    IF NEW.milestone_id IS NOT NULL THEN NEW.milestone_added_at := now(); END IF;
    IF NEW.status = 'in_progress' THEN NEW.started_at := now(); END IF;
    IF NEW.status IN ('done', 'wont_do') THEN NEW.completed_at := COALESCE(NEW.completed_at, now()); END IF;
    NEW.last_activity_at := now();
    RETURN NEW;
  END IF;

  -- UPDATE
  IF NOT v_lead THEN
    IF NEW.milestone_id IS DISTINCT FROM OLD.milestone_id OR NEW.priority IS DISTINCT FROM OLD.priority OR NEW.planned IS DISTINCT FROM OLD.planned
       OR NEW.source IS DISTINCT FROM OLD.source THEN
      RAISE EXCEPTION 'Only the head of IT or the MD can change the milestone, priority or planning of an issue';
    END IF;
    IF NEW.assignee_id IS DISTINCT FROM OLD.assignee_id AND NEW.assignee_id IS DISTINCT FROM auth.uid() AND OLD.assignee_id IS DISTINCT FROM auth.uid() THEN
      RAISE EXCEPTION 'You can take an issue yourself or hand back your own; the head of IT assigns others';
    END IF;
  END IF;
  NEW.created_by := OLD.created_by;
  NEW.created_at := OLD.created_at;
  IF NEW.milestone_id IS DISTINCT FROM OLD.milestone_id THEN NEW.milestone_added_at := CASE WHEN NEW.milestone_id IS NULL THEN NULL ELSE now() END; END IF;
  IF NEW.status = 'in_progress' AND OLD.status <> 'in_progress' AND NEW.started_at IS NULL THEN NEW.started_at := now(); END IF;
  IF NEW.status IN ('done', 'wont_do') AND OLD.status NOT IN ('done', 'wont_do') THEN NEW.completed_at := now(); END IF;
  IF NEW.status NOT IN ('done', 'wont_do') THEN NEW.completed_at := NULL; END IF;
  IF NOT NEW.blocked THEN NEW.blocked_reason := NULL; END IF;
  NEW.updated_at := now();
  NEW.last_activity_at := now();
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS it_issues_before ON it_issues;
CREATE TRIGGER it_issues_before BEFORE INSERT OR UPDATE ON it_issues FOR EACH ROW EXECUTE FUNCTION it_issue_before();

CREATE OR REPLACE FUNCTION it_issue_after() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE a uuid := COALESCE(auth.uid(), NEW.created_by);
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO it_issue_events (issue_id, actor, kind, to_value, at) VALUES (NEW.id, a, 'created', NEW.status, COALESCE(NEW.created_at, now()));
    RETURN NULL;
  END IF;
  IF NEW.status <> OLD.status THEN INSERT INTO it_issue_events (issue_id, actor, kind, from_value, to_value) VALUES (NEW.id, a, 'status', OLD.status, NEW.status); END IF;
  IF NEW.assignee_id IS DISTINCT FROM OLD.assignee_id THEN INSERT INTO it_issue_events (issue_id, actor, kind, from_value, to_value) VALUES (NEW.id, a, 'assigned', OLD.assignee_id::text, NEW.assignee_id::text); END IF;
  IF NEW.milestone_id IS DISTINCT FROM OLD.milestone_id THEN INSERT INTO it_issue_events (issue_id, actor, kind, from_value, to_value) VALUES (NEW.id, a, 'milestone', OLD.milestone_id::text, NEW.milestone_id::text); END IF;
  IF NEW.priority <> OLD.priority THEN INSERT INTO it_issue_events (issue_id, actor, kind, from_value, to_value) VALUES (NEW.id, a, 'priority', OLD.priority, NEW.priority); END IF;
  IF NEW.planned <> OLD.planned THEN INSERT INTO it_issue_events (issue_id, actor, kind, to_value) VALUES (NEW.id, a, 'planned', NEW.planned::text); END IF;
  IF NEW.blocked AND NOT OLD.blocked THEN INSERT INTO it_issue_events (issue_id, actor, kind, body) VALUES (NEW.id, a, 'blocked', NEW.blocked_reason); END IF;
  IF OLD.blocked AND NOT NEW.blocked THEN INSERT INTO it_issue_events (issue_id, actor, kind) VALUES (NEW.id, a, 'unblocked'); END IF;
  -- The person who flagged it hears when it's done.
  IF NEW.status = 'done' AND OLD.status <> 'done' AND NEW.inbox_id IS NOT NULL THEN
    INSERT INTO notification_events (rule_key, payload)
    SELECT 'it_flag_resolved', jsonb_build_object('inbox_id', i.id, 'issue_id', NEW.id, 'recipient_id', i.submitted_by, 'actor_id', auth.uid())
    FROM it_inbox i WHERE i.id = NEW.inbox_id AND i.submitted_by IS NOT NULL;
  END IF;
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS it_issues_after ON it_issues;
CREATE TRIGGER it_issues_after AFTER INSERT OR UPDATE ON it_issues FOR EACH ROW EXECUTE FUNCTION it_issue_after();

-- Comments: always in the writer's own name.
CREATE OR REPLACE FUNCTION it_event_stamp() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NOT NULL THEN NEW.actor := auth.uid(); NEW.at := now(); END IF;
  IF NEW.kind = 'comment' THEN UPDATE it_issues SET last_activity_at = now() WHERE id = NEW.issue_id; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS it_issue_events_stamp ON it_issue_events;
CREATE TRIGGER it_issue_events_stamp BEFORE INSERT ON it_issue_events FOR EACH ROW EXECUTE FUNCTION it_event_stamp();

CREATE OR REPLACE FUNCTION it_inbox_notify() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO notification_events (rule_key, payload) VALUES ('it_flag_created', jsonb_build_object('inbox_id', NEW.id, 'actor_id', NEW.submitted_by));
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS it_inbox_notify ON it_inbox;
CREATE TRIGGER it_inbox_notify AFTER INSERT ON it_inbox FOR EACH ROW WHEN (NEW.status = 'new') EXECUTE FUNCTION it_inbox_notify();

