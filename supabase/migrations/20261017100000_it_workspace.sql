CREATE OR REPLACE FUNCTION is_it_member() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT is_managing_director() OR EXISTS (SELECT 1 FROM it_members WHERE profile_id = auth.uid()) OR current_department_slug() = 'it';
$$;
CREATE OR REPLACE FUNCTION is_it_lead() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT is_managing_director() OR EXISTS (SELECT 1 FROM it_members WHERE profile_id = auth.uid() AND role IN ('head', 'md'));
$$;

