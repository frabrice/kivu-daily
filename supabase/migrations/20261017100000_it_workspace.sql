-- Anyone can send IT a request (Flag to IT, Submit to IT); it lands in the inbox.
CREATE OR REPLACE FUNCTION submit_to_it(p jsonb) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id uuid;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Sign in first'; END IF;
  IF NULLIF(trim(p->>'title'), '') IS NULL THEN RAISE EXCEPTION 'Say what you need'; END IF;
  INSERT INTO it_inbox (title, details, persona, acceptance_criteria, entity_type, entity_id, entity_label, submitted_by)
  VALUES (trim(p->>'title'), NULLIF(trim(p->>'details'), ''), NULLIF(trim(p->>'persona'), ''), COALESCE(p->'acceptance_criteria', '[]'::jsonb),
          NULLIF(p->>'entity_type', ''), NULLIF(p->>'entity_id', '')::uuid, NULLIF(p->>'entity_label', ''), auth.uid())
  RETURNING id INTO v_id;
  RETURN v_id;
END $$;

-- The old Flag to IT button keeps working, now into the inbox.
CREATE OR REPLACE FUNCTION flag_to_it(p_entity_type text, p_entity_id uuid, p_entity_label text, p_persona text, p_need text, p_details text, p_acceptance_criteria jsonb DEFAULT '[]'::jsonb)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  RETURN submit_to_it(jsonb_build_object('title', p_need, 'details', p_details, 'persona', p_persona, 'acceptance_criteria', COALESCE(p_acceptance_criteria, '[]'::jsonb),
    'entity_type', p_entity_type, 'entity_id', p_entity_id, 'entity_label', p_entity_label));
END $$;

-- Triage: accept (-> new issue), merge into an issue, park or decline.
CREATE OR REPLACE FUNCTION triage_it_inbox(p_id uuid, p_action text, p_issue jsonb DEFAULT NULL, p_merge_into bigint DEFAULT NULL, p_note text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_in it_inbox%ROWTYPE; v_issue bigint;
BEGIN
  IF NOT is_it_lead() THEN RAISE EXCEPTION 'Only the head of IT or the MD can triage requests'; END IF;
  SELECT * INTO v_in FROM it_inbox WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Request not found'; END IF;
  IF p_action = 'accept' THEN
    INSERT INTO it_issues (title, description, type, areas, priority, size, assignee_id, milestone_id, source, acceptance_criteria, inbox_id, labels)
    VALUES (COALESCE(NULLIF(trim(p_issue->>'title'), ''), v_in.title),
            COALESCE(NULLIF(trim(p_issue->>'description'), ''), concat_ws(E'\n\n', v_in.details, CASE WHEN v_in.entity_label IS NOT NULL THEN 'About: ' || v_in.entity_label END)),
            COALESCE(p_issue->>'type', 'improvement'), COALESCE((SELECT array_agg(x) FROM jsonb_array_elements_text(p_issue->'areas') x), '{}'),
            COALESCE(p_issue->>'priority', 'p2'), NULLIF(p_issue->>'size', ''), NULLIF(p_issue->>'assignee_id', '')::uuid, NULLIF(p_issue->>'milestone_id', '')::uuid,
            'department', v_in.acceptance_criteria, v_in.id, '{}')
    RETURNING id INTO v_issue;
  ELSIF p_action = 'merge' THEN
    IF NOT EXISTS (SELECT 1 FROM it_issues WHERE id = p_merge_into) THEN RAISE EXCEPTION 'Issue KR-% not found', p_merge_into; END IF;
    v_issue := p_merge_into;
    INSERT INTO it_issue_events (issue_id, kind, body) VALUES (v_issue, 'comment', 'Merged request: ' || v_in.title || COALESCE(E'\n' || v_in.details, ''));
  ELSIF p_action IN ('park', 'decline') THEN
    IF p_action = 'decline' AND NULLIF(trim(p_note), '') IS NULL THEN RAISE EXCEPTION 'Say why it is declined - the person who asked will see it'; END IF;
  ELSE
    RAISE EXCEPTION 'Unknown action';
  END IF;
  UPDATE it_inbox SET status = CASE p_action WHEN 'accept' THEN 'accepted' WHEN 'merge' THEN 'merged' WHEN 'park' THEN 'parked' ELSE 'declined' END,
    issue_id = v_issue, decision_note = NULLIF(trim(p_note), ''), decided_by = auth.uid(), decided_at = now()
  WHERE id = p_id;
  RETURN v_issue;
END $$;

-- "What are you working on?" - confirm the issue (it goes In progress, in your name).
CREATE OR REPLACE FUNCTION confirm_it_work(p_issue bigint, p_note text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_today date := (now() AT TIME ZONE 'Africa/Kigali')::date; v_slot text; v_i it_issues%ROWTYPE;
BEGIN
  IF NOT is_it_member() THEN RAISE EXCEPTION 'Only the IT team checks in'; END IF;
  SELECT * INTO v_i FROM it_issues WHERE id = p_issue;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue not found'; END IF;
  IF v_i.assignee_id IS NOT NULL AND v_i.assignee_id <> auth.uid() THEN RAISE EXCEPTION 'KR-% is assigned to someone else - ask the head of IT', p_issue; END IF;
  IF v_i.status IN ('done', 'wont_do') THEN RAISE EXCEPTION 'KR-% is already closed', p_issue; END IF;
  UPDATE it_issues SET assignee_id = auth.uid(), status = CASE WHEN status IN ('backlog', 'ready') THEN 'in_progress' ELSE status END WHERE id = p_issue;
  -- Answer the latest open question today, or record it on its own.
  SELECT slot INTO v_slot FROM it_checkins WHERE profile_id = auth.uid() AND day = v_today AND confirmed_at IS NULL ORDER BY asked_at DESC NULLS LAST LIMIT 1;
  IF v_slot IS NULL THEN
    INSERT INTO it_checkins (profile_id, day, slot, confirmed_at, issue_id, note) VALUES (auth.uid(), v_today, 'self', now(), p_issue, NULLIF(trim(p_note), ''))
    ON CONFLICT (profile_id, day, slot) DO UPDATE SET confirmed_at = now(), issue_id = EXCLUDED.issue_id, note = EXCLUDED.note;
  ELSE
    UPDATE it_checkins SET confirmed_at = now(), issue_id = p_issue, note = NULLIF(trim(p_note), '') WHERE profile_id = auth.uid() AND day = v_today AND confirmed_at IS NULL;
  END IF;
END $$;

DO $$
DECLARE f text;
BEGIN
  FOREACH f IN ARRAY ARRAY['is_it_member()', 'is_it_lead()', 'submit_to_it(jsonb)', 'triage_it_inbox(uuid, text, jsonb, bigint, text)', 'confirm_it_work(bigint, text)',
    'it_issue_before()', 'it_issue_after()', 'it_event_stamp()', 'it_inbox_notify()'] LOOP
    EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC, anon', f);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO authenticated', f);
  END LOOP;
END $$;

